// Command vcluster-role prints the rules the control plane of a vcluster
// machine needs in its instance namespace, as the embedded chart grants them
// (config/rbac/vcluster-role.yaml). The platform chart turns them into the
// ClusterRole the operator binds in each instance namespace.
package main

import (
	"fmt"
	"os"

	rbacv1 "k8s.io/api/rbac/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/yaml"

	"github.com/Sigeth/brokelabs-core-go/pkg/project"
	"github.com/Sigeth/brokelabs-operator/internal/vcluster"
)

func main() {
	rules, err := vcluster.RoleRules()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	role := rbacv1.ClusterRole{
		TypeMeta:   metav1.TypeMeta{APIVersion: rbacv1.SchemeGroupVersion.String(), Kind: "ClusterRole"},
		ObjectMeta: metav1.ObjectMeta{Name: project.Name + "-vcluster"},
		Rules:      rules,
	}
	out, err := yaml.Marshal(role)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("# Generated by cmd/vcluster-role from the vcluster chart %s: do not edit.\n---\n%s", vcluster.ChartVersion, out)
}
